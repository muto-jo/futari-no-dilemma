import type { Nav, Screen } from '../app.ts';
import { button, h } from '../dom.ts';

const sec = (title: string, ...items: (string | HTMLElement)[]) =>
  h('section', { class: 'panel rules' }, h('h3', null, title), h('ul', null, items.map((x) => h('li', null, x))));

